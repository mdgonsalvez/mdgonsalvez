//  CountryDatabase.swift
//  PassportQuest
//
//  The complete seeded country data set (~195 UN-recognised countries plus a
//  small Polar & Territories section). All data is bundled — there are no
//  network calls at runtime (spec rule #2). Facts, capitals, currencies and
//  national animals are accurate to the best of available training data.
//
//  Silhouette coverage: `silhouetteAvailable: true` is set for the 30 most
//  recognisable country shapes, whose normalised Paths live in
//  SilhouettePaths.swift. All other countries fall back to a continent
//  placeholder silhouette with a question mark.
//
//  Curated Easy unlocks: `isCuratedEasyUnlock: true` marks the ~8 most
//  recognisable countries per continent, surfaced first on Easy mode.
//

import Foundation

/// Central access point for the seeded country data.
enum CountryDatabase {

    /// The full, immutable list of countries.
    static let all: [Country] = europe + americas + asia + africa + oceania + polar

    /// Lookup by ISO alpha-2 id.
    static let byID: [String: Country] = Dictionary(uniqueKeysWithValues: all.map { ($0.id, $0) })

    static func country(id: String) -> Country? { byID[id] }

    static func countries(in continent: Continent) -> [Country] {
        all.filter { $0.continent == continent }
    }

    static func curatedEasy(in continent: Continent) -> [Country] {
        countries(in: continent).filter { $0.isCuratedEasyUnlock }
    }

